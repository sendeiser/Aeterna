def clean_name(raw_name):
    if not raw_name:
        return ""
    raw = raw_name.strip()
    
    # Check if parcela disponible
    if "PARCELA" in raw.upper() and "DISPONIBLE" in raw.upper():
        return ""
    if "MUNICIPALIDAD" in raw.upper():
        return "Municipalidad de Chamical"
        
    return raw

def format_title_case(name_str):
    if not name_str:
        return ""
    words = name_str.split()
    lowers = {"de", "del", "la", "las", "los", "y", "da", "di", "e"}
    res = []
    for i, w in enumerate(words):
        lw = w.lower()
        if i > 0 and lw in lowers:
            res.append(lw)
        elif w.startswith("(") and w.endswith(")"):
            res.append(w.title())
        elif w.upper() == "N°":
            res.append("N°")
        elif "." in w:
            res.append(w.upper())
        else:
            res.append(w.capitalize())
    return " ".join(res)

